'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const ids = require('../src/question-identity.js');
assert.ok(html.includes('<script src="src/question-identity.js"></script><script>'),'module must load before app');
assert.match(html, /function progressKey\(y,c,n,examId='db'\)/);
assert.match(html, /DBStudyQuestionIdentity\.format\(\{examId,year:y,courseId:c,number:n\}\)/);
assert.match(html, /DBStudyQuestionIdentity\.toLegacy\(qualified\)\|\|qualified/);
assert.match(html, /function rec\(\)\{const id=progressKey\(year,courseId,number\)/);
assert.match(html, /function put\(update\)\{const id=progressKey\(year,courseId,number\)/);
assert.equal((html.match(/progress\[progressKey\(year,x\.id,i\+1\)\]/g)||[]).length, 2);
assert.ok(html.includes('progress[progressKey(year,courseId,i)]'));
assert.ok(html.includes("const KEY='db-study-progress-v1'"),'legacy local data must remain');
assert.ok(html.includes("format:'db-study-backup-v1',progress"),'legacy backup must remain');
assert.ok(html.includes("x.format!=='db-study-backup-v1'"),'legacy restore must remain');
assert.equal(ids.toLegacy(ids.format({examId:'db',year:2025,courseId:'am2',number:1})), '2025:am2:1');
assert.equal(ids.toLegacy(ids.format({examId:'pm',year:2025,courseId:'am2',number:1})), null);
assert.equal(ids.normalize('2025:am2:1'), 'db:2025:am2:1');
console.log('UI key integration and legacy backup/storage compatibility: PASS');
